import Ajv from "ajv";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import schema from "../schema/map.schema.json" with { type: "json" };

// Generate once in Node, never execute Ajv's schema compiler in the browser.
// This keeps script-src 'self' without unsafe-eval.
const ajv = new Ajv({
  allErrors: true,
  strict: true,
  code: { source: true, esm: true, lines: true },
});
addFormats(ajv);
const validate = ajv.compile(schema);
let source = standaloneCode(ajv, validate);
const dependencies = new Map<string, string>();
source = source.replace(/require\("([^"]+)"\)/g, (_match, name: string) => {
  if (!dependencies.has(name))
    dependencies.set(name, `__required${dependencies.size}`);
  return dependencies.get(name)!;
});
const imports = [...dependencies]
  .map(([name, alias], index) => {
    const specifier = name.endsWith(".js") ? name : name + ".js";
    // Node and Vite represent CommonJS namespaces differently; normalize without eval.
    return `import * as __namespace${index} from ${JSON.stringify(specifier)};\nconst ${alias} = __namespace${index}.default?.__esModule ? __namespace${index}.default : __namespace${index};`;
  })
  .join("\n");
const output =
  "// Generated by npm run schema:generate. Do not edit.\n" +
  imports +
  "\n" +
  source +
  "\n";
const target = path.resolve("src/generated/map-validator.js");
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")).replace(/\r\n/g, "\n") !== output) {
    throw new Error(
      "数据 Schema 与预编译校验器不一致，请运行 npm run schema:generate",
    );
  }
  console.log("Schema 预编译校验器一致。");
} else {
  await writeFile(target, output, "utf8");
  console.log("已生成无动态求值的浏览器校验器。");
}
